def replace_entry(content: str, new_scene: str) -> str:
    new_block = f"## 入口场景\n\n{new_scene.strip()}\n"
    if not re.search(r"^## 入口场景\s*\n", content, re.M):
        raise ValueError("missing 入口场景 section")
    return re.sub(
        r"^## 入口场景\s*\n.*?(?=^## |\Z)",
        new_block + "\n",
        content,
        count=1,
        flags=re.M | re.S,
    )


def main():
    jsonl = LIB / "output" / "entry-scene-remaining.jsonl"
    items = [json.loads(line) for line in jsonl.read_text().splitlines() if line.strip()]
    results = []

    for it in items:
        stem = it["stem"]
        path = CONCEPT_DIR / it["file"]
        if stem not in SCENES:
            results.append((stem, 0, "missing scene text"))
            continue
        content = path.read_text(encoding="utf-8")
        new_content = replace_entry(content, SCENES[stem])
        path.write_text(new_content, encoding="utf-8")

        lint = subprocess.run(
            ["python3", str(SCRIPTS / "lint_concepts.py"), "--file", stem],
            capture_output=True,
            text=True,
        )
        sync = subprocess.run(
            ["python3", str(SCRIPTS / "sync_db.py"), "--file", stem],
            capture_output=True,
            text=True,
        )

        entry_m = re.search(r"^## 入口场景\s*\n(.*?)(?=^## |\Z)", new_content, re.M | re.S)
        entry = entry_m.group(1).strip() if entry_m else ""
        cn = len(re.findall(r"[\u4e00-\u9fff]", entry))

        lint_ok = lint.returncode == 0 and "全部通过" in lint.stdout
        sync_ok = sync.returncode == 0
        fail_parts = []
        if not lint_ok:
            fail_parts.append("lint:" + (lint.stdout or lint.stderr)[:200])
        if not sync_ok:
            fail_parts.append("sync:" + (sync.stderr or sync.stdout)[:200])
        results.append((stem, cn, "; ".join(fail_parts) if fail_parts else "OK"))

    print(f"{'stem':<16} {'chars':>5}  status")
    print("-" * 40)
    for stem, cn, status in results:
        print(f"{stem:<16} {cn:>5}  {status}")


if __name__ == "__main__":
    main()